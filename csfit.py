def primary_category(title: str, entities: str = "") -> str:
    """대표 범주. RULES 가 가중치 내림차순이라 첫 매치가 가장 무거운 범주다.

    **제목만 본다. entities 는 쓰지 않는다.**
    모델이 main_entities 에 "관련 있는" 회사를 폭넓게 적어서, 한화 얘기가
    아닌 기사도 한화생명이 목록에 있다는 이유로 [한화] 로 분류됐다.
    실제 사고: "보험사 GA 관리 평가 지표 마련" 이 [한화] 로 잡혀 한화 상한을
    먹었고, 정작 애큐온·방카슈랑스 같은 진짜 한화 기사가 밀려났다(2026-10-02).

    점수(score)는 entities 를 계속 본다 — 관련성 신호로는 쓸모가 있다.
    범주 분류만 제목으로 한다. "이 기사가 무엇에 대한 것인가" 는 제목이 말한다.
    """
    for name, pat, _w in RULES:
        if re.search(pat, title or "", re.I):
            return name
    return "기타"


