def score(title: str, entities: str = "", primary_topic: str = "",
          strategic_score: int | None = None) -> tuple[int, list[str]]:
    """(적합도, 걸린 규칙 이름들). 0~100 으로 자른다."""
    text = f"{title} {entities or ''}"
    hits, weights = [], []
    for name, pat, w in RULES:
        if re.search(pat, text, re.I):
            weights.append(w)
            hits.append(name)

    # **주 범주가 결정하고 보조 범주는 약하게만 더한다.**
    # 단순 합산이던 때, 여러 범주에 걸치는 기사가 구조적으로 유리했다.
    # GA·보험 기사는 경쟁보험사(22)+자본(7)+채널(6)+규제(11)를 한꺼번에 먹어
    # 85~100점이 되고, 글로벌 기사는 15점짜리 하나라 54점에 그쳤다.
    # 그 결과 Top10 의 주제 분포가 A팀 실측과 119%p 어긋났다(후보 풀 자체는
    # 65%p 였으니 순위 단계가 편차를 두 배로 키운 셈이다).
    # 보조 반영률별 실측 편차: 1.0 → 119 / 0.5 → 95 / 0.2 → 87 / 0.0 → 78
    # 0 으로 두면 분포는 가장 잘 맞지만 "한화 + M&A + 규제" 같은 복합 사안이
    # 단일 범주 기사와 동점이 된다. 0.2 로 절충한다.
    pts = 0
    if weights:
        pts = max(weights) + SECONDARY_WEIGHT * (sum(weights) - max(weights))
    for name, pat, w in NEGATIVE:
        if re.search(pat, text, re.I):
            pts += w
            hits.append(f"-{name}")


    # 모델이 매긴 전략성도 섞는다. 적합도가 주, strategic_score 가 보조다.
    # 주제는 맞는데 알맹이가 없는 기사를 걸러내는 역할.
    if strategic_score is not None:
        pts += int(strategic_score * 0.25)

    return max(0, min(100, int(pts))), hits


