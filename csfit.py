def foreign_verdict(title: str, entities: str = "",
                    hits: list | None = None) -> tuple[bool, str]:
    """해외 기사를 받을지. (받는다, 이유)

    해외 기사가 아니면 항상 (True, ""). 위 주석의 네 갈래를 코드로 옮긴 것이다.
    """
    text = f"{title} {entities or ''}"
    if hits is None:
        hits = [n for n, pat, _ in RULES if re.search(pat, text, re.I)]
    if "글로벌" not in hits:
        return True, ""
    if KOREAN_ANCHOR.search(text):
        return True, "한국·한화 앵커"
    axis = [h for h in hits if h in FOREIGN_OK_CATS]
    # **'경쟁 보험사' 축은 일반명사만으로 인정하지 않는다.**
    # 그 범주 정규식에 `생보|손보|보험사|보험업계` 가 들어 있어, "보험사"
    # 라는 일반명사가 제목에 있기만 하면 해외 기사가 전부 통과했다.
    # 실측: "알리안츠, 3분기 영업이익 사상 최대…유럽 생보 호조",
    # "싱가포르 생보사, 여행자보험 앱 리뉴얼" 이 fit 37 로 통과했다.
    # "닛폰생명" 이라 쓰면 기각되고 "생보" 라 쓰면 통과하는 자의적 결과였다.
    # 국내 경쟁사 고유명이 실제로 있을 때만 축으로 친다(2026-10-05 감사).
    if "경쟁 보험사" in axis and not _KR_INSURER.search(text):
        axis = [h for h in axis if h != "경쟁 보험사"]
    if axis:
        return True, "참고 축: " + "·".join(axis)
    return False, "해외 단독(한국 앵커·참고 축 없음)"


